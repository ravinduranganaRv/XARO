"""Builds src/mod/quote_preset_xaro.js: the XARO Industries quotation template image (A4 landscape) embedded as a data URI.
usage: python3 tools/make_quote_preset.py <template.png>"""
import sys, base64, io
from PIL import Image
im = Image.open(sys.argv[1]).convert('RGB').resize((1754, 1240), Image.LANCZOS)
b = io.BytesIO(); im.save(b, 'JPEG', quality=86, optimize=True, progressive=True)
open('assets/xaro-quotation-template.jpg', 'wb').write(b.getvalue())
open('src/mod/quote_preset_xaro.js', 'w').write("/* generated by tools/make_quote_preset.py: XARO Industries quotation template, A4 landscape */\n(function (root) { 'use strict'; if (root.XQUOTE) root.XQUOTE.PRESETS.xaro.src = 'data:image/jpeg;base64," + base64.b64encode(b.getvalue()).decode() + "'; })(typeof window !== 'undefined' ? window : globalThis);\n")
print(len(b.getvalue()), 'bytes')
